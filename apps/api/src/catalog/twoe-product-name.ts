export function normalizeTwoESku(model: string): string {
  return model
    .trim()
    .toUpperCase()
    .replace(/\s+/g, '-')
    .replace(/[^A-Z0-9._-]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export function twoeSkuForGenerator(model: string): string {
  const sku = normalizeTwoESku(model);
  return TWOE_GENERATOR_MODELS[sku] ?? sku;
}

