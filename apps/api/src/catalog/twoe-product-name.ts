function collapseWhitespace(value: string): string {
  return value.replace(/\s+/g, ' ').trim();
}

export function twoeDisplayModel(sku: string, fallbackTitle: string): string {
  const catalogName = resolveTwoECatalogName(sku, fallbackTitle);
  let model = catalogName.replace(/^2E(?:\s+Gaming)?\s+/i, '').trim();
  for (const suffix of TYPE_SUFFIXES) {
    const pattern = new RegExp(`\\s+${suffix.replaceAll(' ', '\\s+')}$`, 'i');
    if (pattern.test(model)) {
      model = model.replace(pattern, "").trim();
      break;
    }
  }
  return model;
}

export function resolveTwoECatalogName(
  sku: string,
  fallbackTitle: string,
): string {
  const normalized = normalizeTwoESku(sku);
  const mapped = TWOE_CATALOG_NAMES[normalized];
  if (mapped !== undefined) {
    return mapped;
  }
  const trimmed = collapseWhitespace(fallbackTitle);
  if (/^2e\b/i.test(trimmed)) {
    return trimmed;
  }
  if (trimmed === "") {
    return `2E ${normalized}`;
  }
  return `2E ${trimmed}`;
}

