function colorKey(sku) {
  return sku.replace(/[^A-Za-z0-9]/g, '').toUpperCase();
}

function colorFor(sku) {
  if (COLOR_BY_SKU[sku]) return COLOR_BY_SKU[sku];
  const compact = colorKey(sku);
  for (const [key, value] of Object.entries(COLOR_BY_SKU)) {
    if (colorKey(key) === compact) return value;
  }
  return '';
}

function resolveFamily(sku) {
  const upper = sku.toUpperCase().trim();
  const keys = Object.keys(MODELS).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    if (upper === key || upper.startsWith(`${key} `) || upper.startsWith(key)) {
      return key;
    }
  }
  return null;
}

